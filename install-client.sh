#!/usr/bin/env bash
set -euo pipefail

_FRP_INSTALL_CLIENT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [[ -f "${_FRP_INSTALL_CLIENT_DIR}/VERSION" ]]; then
  # shellcheck disable=SC1091
  . "${_FRP_INSTALL_CLIENT_DIR}/VERSION"
fi
PROJECT_VERSION="${PROJECT_VERSION:-1.3.0}"
FRP_VERSION="${FRP_VERSION:-0.70.1}"
FRP_SHA256_AMD64="333da23d1b9009d7c01638e9ba38cf4600f7d37d393f854e96ee1396adefa9a6"
FRP_SHA256_ARM64="3990f396a9a490ee7f0e5f355287750ed41520064ed999eab443b5e9a78d773d"

# shellcheck source=lib/frp-client-common.sh
. "${_FRP_INSTALL_CLIENT_DIR}/lib/frp-client-common.sh"

frp_valid_allocator_url() {
  local url="${1:-}"
  case "$url" in
    http://?*|https://?*) ;;
    *) return 1 ;;
  esac
  if [[ "$url" == *$'\n'* || "$url" == *$'\r'* || "$url" == *$'\t'* || "$url" == *' '* ]]; then
    return 1
  fi
  local rest="${url#*://}"
  local hostport="${rest%%/*}"
  [[ -n "$hostport" ]]
}

frp_require_allocator_url() {
  local url="${FRP_ALLOCATOR_URL:-}"
  if [[ -z "$url" ]]; then
    echo "ERROR: FRP allocator URL is not configured." >&2
    echo "Set FRP_ALLOCATOR_URL or use the installer command generated by frp-create-client." >&2
    exit 1
  fi
  if ! frp_valid_allocator_url "$url"; then
    echo "ERROR: FRP allocator URL is invalid; an http:// or https:// URL with a host is required." >&2
    exit 1
  fi
  ALLOCATOR_URL="$url"
}

frp_os_release_file() {
  printf '%s' "${FRP_OS_RELEASE_FILE:-/etc/os-release}"
}

frp_os_release_value() {
  local key="$1" file="$2" line value
  [[ -r "$file" ]] || return 0
  while IFS= read -r line || [[ -n "$line" ]]; do
    case "$line" in
      "${key}="*)
        value="${line#*=}"
        if [[ "$value" == \"*\" ]]; then
          value="${value#\"}"
          value="${value%\"}"
        elif [[ "$value" == \'*\' ]]; then
          value="${value#\'}"
          value="${value%\'}"
        fi
        printf '%s' "$value"
        return 0
        ;;
    esac
  done <"$file"
}

frp_detect_platform() {
  local file pretty name
  DISTRO_ID="unknown"
  DISTRO_NAME="Linux"
  DISTRO_VERSION=""
  file="$(frp_os_release_file)"
  if [[ -r "$file" ]]; then
    DISTRO_ID="$(frp_os_release_value ID "$file")"
    DISTRO_ID="${DISTRO_ID:-unknown}"
    pretty="$(frp_os_release_value PRETTY_NAME "$file")"
    name="$(frp_os_release_value NAME "$file")"
    DISTRO_NAME="${pretty:-${name:-Linux}}"
    DISTRO_VERSION="$(frp_os_release_value VERSION_ID "$file")"
  fi
}

frp_detect_architecture() {
  local machine
  machine="${FRP_TEST_UNAME_M:-$(uname -m)}"
  case "$machine" in
    x86_64)
      FRP_ARCH=amd64
      EXPECTED_SHA="$FRP_SHA256_AMD64"
      ;;
    aarch64|arm64)
      FRP_ARCH=arm64
      EXPECTED_SHA="$FRP_SHA256_ARM64"
      ;;
    *)
      echo "ERROR: unsupported architecture: ${machine}" >&2
      return 1
      ;;
  esac
}

frp_command_exists() {
  local cmd="$1"
  if [[ -n "${FRP_TEST_CMD_PATH:-}" ]]; then
    PATH="${FRP_TEST_CMD_PATH}" command -v "$cmd" >/dev/null 2>&1
  else
    command -v "$cmd" >/dev/null 2>&1
  fi
}

frp_package_manager_exists() {
  local cmd="$1"
  if [[ -n "${FRP_TEST_PM_PATH:-}" ]]; then
    PATH="${FRP_TEST_PM_PATH}" command -v "$cmd" >/dev/null 2>&1
  else
    command -v "$cmd" >/dev/null 2>&1
  fi
}

frp_package_manager_bin() {
  local cmd="$1"
  if [[ -n "${FRP_TEST_PM_PATH:-}" ]]; then
    PATH="${FRP_TEST_PM_PATH}" command -v "$cmd"
  else
    command -v "$cmd"
  fi
}

frp_detect_package_manager() {
  PACKAGE_MANAGER=""
  if frp_package_manager_exists dnf; then
    PACKAGE_MANAGER=dnf
  elif frp_package_manager_exists yum; then
    PACKAGE_MANAGER=yum
  elif frp_package_manager_exists apt-get; then
    PACKAGE_MANAGER=apt
  fi
}

frp_systemd_runtime_dir() {
  printf '%s' "${FRP_TEST_SYSTEMD_RUNTIME_DIR:-/run/systemd/system}"
}

frp_systemd_usable() {
  [[ -d "$(frp_systemd_runtime_dir)" ]]
}

frp_require_systemd() {
  if ! frp_command_exists systemctl; then
    echo "ERROR: this release requires a systemd-based Linux distribution." >&2
    return 1
  fi
  if ! frp_systemd_usable; then
    echo "ERROR: this release requires a systemd-based Linux distribution." >&2
    return 1
  fi
}

frp_print_detected_linux() {
  local pm="${PACKAGE_MANAGER:-none}"
  local init="unknown"
  if frp_command_exists systemctl && frp_systemd_usable; then
    init="systemd"
  fi
  echo "Detected Linux:"
  echo "  Distribution : ${DISTRO_NAME}"
  echo "  Package mgr  : ${pm}"
  echo "  Architecture : ${FRP_ARCH}"
  echo "  Init system  : ${init}"
}

frp_required_commands() {
  printf '%s\n' curl openssl python3 tar sha256sum timeout hostname install
}

frp_collect_missing_commands() {
  local cmd
  MISSING_COMMANDS=()
  while IFS= read -r cmd; do
    [[ -n "$cmd" ]] || continue
    if ! frp_command_exists "$cmd"; then
      MISSING_COMMANDS+=("$cmd")
    fi
  done < <(frp_required_commands)
}

frp_package_for_command() {
  local cmd="$1" pm="$2"
  case "$cmd" in
    curl) printf 'curl' ;;
    openssl) printf 'openssl' ;;
    python3) printf 'python3' ;;
    tar) printf 'tar' ;;
    sha256sum|timeout|install) printf 'coreutils' ;;
    hostname) printf 'hostname' ;;
    ss|ip)
      if [[ "$pm" == apt ]]; then
        printf 'iproute2'
      else
        printf 'iproute'
      fi
      ;;
    *)
      echo "ERROR: no package mapping for command: ${cmd}" >&2
      return 1
      ;;
  esac
}

frp_packages_for_missing() {
  local pm="$1" cmd pkg existing existing_pkg
  PACKAGES=(ca-certificates)
  for cmd in "${MISSING_COMMANDS[@]}"; do
    pkg="$(frp_package_for_command "$cmd" "$pm")"
    existing=0
    for existing_pkg in "${PACKAGES[@]}"; do
      if [[ "$existing_pkg" == "$pkg" ]]; then
        existing=1
        break
      fi
    done
    if (( existing == 0 )); then
      PACKAGES+=("$pkg")
    fi
  done
}

install_dependencies_apt() {
  local bin
  bin="$(frp_package_manager_bin apt-get)"
  export DEBIAN_FRONTEND=noninteractive
  "$bin" update
  "$bin" install -y --no-install-recommends "$@"
}

install_dependencies_dnf() {
  local bin
  bin="$(frp_package_manager_bin dnf)"
  "$bin" install -y "$@"
}

install_dependencies_yum() {
  local bin
  bin="$(frp_package_manager_bin yum)"
  "$bin" install -y "$@"
}

frp_print_missing_tools_error() {
  local cmd
  echo "ERROR: required tools are missing:" >&2
  for cmd in "${MISSING_COMMANDS[@]}"; do
    echo "  ${cmd}" >&2
  done
  echo >&2
  echo "Automatic dependency installation supports apt, dnf, and yum." >&2
  echo "Install the missing tools manually and run the installer again." >&2
}

ensure_dependencies() {
  frp_collect_missing_commands
  if ((${#MISSING_COMMANDS[@]} == 0)); then
    return 0
  fi
  if [[ -z "${PACKAGE_MANAGER:-}" ]]; then
    frp_detect_package_manager
  fi
  if [[ -z "${PACKAGE_MANAGER:-}" ]]; then
    frp_print_missing_tools_error
    return 1
  fi
  frp_packages_for_missing "$PACKAGE_MANAGER"
  case "$PACKAGE_MANAGER" in
    apt) install_dependencies_apt "${PACKAGES[@]}" ;;
    dnf) install_dependencies_dnf "${PACKAGES[@]}" ;;
    yum) install_dependencies_yum "${PACKAGES[@]}" ;;
    *)
      echo "ERROR: unsupported package manager: ${PACKAGE_MANAGER}" >&2
      return 1
      ;;
  esac
  frp_collect_missing_commands
  if ((${#MISSING_COMMANDS[@]} > 0)); then
    echo "ERROR: missing required command after dependency installation:" >&2
    local cmd
    for cmd in "${MISSING_COMMANDS[@]}"; do
      echo "  ${cmd}" >&2
    done
    return 1
  fi
}

menu_add_service() {
  local payload=""
  frp_ux_prompt_new_service payload
  if [[ -z "$payload" ]]; then
    return 0
  fi
  if ! services_add_json "$payload"; then
    return 0
  fi
}

menu_remove_service() {
  local choice
  if [[ "$(services_count)" == "0" ]]; then
    echo "ERROR: no services to remove" >&2
    return 0
  fi
  echo
  echo "Configured services"
  echo "==================="
  echo
  services_list
  echo "Remove from this install list only."
  echo "Nothing has been published yet, so no public port is reserved."
  echo
  choice="$(read_tty "Remove service number: " "")"
  if ! services_remove_index "$choice"; then
    return 0
  fi
}

collect_services_interactive() {
  local choice payload
  while true; do
    echo
    if [[ "$(services_count)" == "0" ]]; then
      frp_ux_empty_services_help
      echo "1) Add service"
      echo "2) Remove a service"
      echo "3) Install and connect"
      echo "4) Cancel"
      echo
      choice="$(read_tty "Select an option [1]: " "1")"
    else
      echo "Configured services"
      echo "==================="
      echo
      services_list
      frp_ux_configured_services_help
      echo "1) Add another service"
      echo "2) Remove a service"
      echo "3) Install and connect"
      echo "4) Cancel"
      echo
      choice="$(read_tty "Select: " "")"
    fi
    case "$choice" in
      1) menu_add_service ;;
      2) menu_remove_service ;;
      3)
        if [[ "$(services_count)" == "0" ]]; then
          echo "ERROR: at least one service must be configured" >&2
          continue
        fi
        frp_ux_print_install_summary "$SERVICES_FILE" "$FRP_VERSION"
        if frp_confirm_yes "Continue? [Y/n]: "; then
          return 0
        fi
        echo "Returning to the service configuration menu."
        ;;
      4)
        echo "Cancelled."
        return 1
        ;;
      *) echo "ERROR: select 1-4" >&2 ;;
    esac
  done
}

collect_services() {
  services_init
  if [[ -n "${FRP_SERVICES_JSON:-}" ]]; then
    services_load_from_env
    if [[ "$(services_count)" == "0" ]]; then
      echo "ERROR: at least one service must be configured" >&2
      exit 1
    fi
    return 0
  fi
  collect_services_interactive || exit 1
}

